// Writes src/api/schema.gen.ts from openapi.json, the description of the routes the backend builds and a backend
// test keeps current. The output is not tracked: a changed route or record changes it, and the type check then
// fails wherever the client used the old shape.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const doc = JSON.parse(readFileSync(new URL('openapi.json', root), 'utf8'));
const schemas = doc.components?.schemas ?? {};

const ident = (name) => name.replace(/[^A-Za-z0-9_]/g, '_');
const key = (name) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : JSON.stringify(name));

function primitive(type, schema, indent) {
  switch (type) {
    case 'null':
      return 'null';
    case 'string':
      return 'string';
    case 'boolean':
      return 'boolean';
    case 'integer':
    case 'number':
      return 'number';
    case 'array':
      return `Array<${typeOf(schema.items ?? {}, indent)}>`;
    case 'object':
      return objectOf(schema, indent);
    default:
      return 'unknown';
  }
}

function objectOf(schema, indent) {
  const inner = `${indent}  `;
  const required = new Set(schema.required ?? []);
  const lines = Object.entries(schema.properties ?? {}).map(
    ([name, value]) => `${inner}${key(name)}${required.has(name) ? '' : '?'}: ${typeOf(value, inner)};`,
  );
  if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
    lines.push(`${inner}[name: string]: ${typeOf(schema.additionalProperties, inner)};`);
  } else if (lines.length === 0) {
    return 'Record<string, unknown>';
  }
  return `{\n${lines.join('\n')}\n${indent}}`;
}

function typeOf(schema, indent = '') {
  if (schema.$ref) {
    return ident(schema.$ref.split('/').pop());
  }
  if (schema.enum) {
    return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  }
  if (schema.oneOf || schema.anyOf) {
    return (schema.oneOf ?? schema.anyOf).map((s) => typeOf(s, indent)).join(' | ');
  }
  if (Array.isArray(schema.type)) {
    // A number is described as a number or its text (the reader accepts both). The backend writes the number.
    const numeric = schema.type.includes('integer') || schema.type.includes('number');
    const types = numeric && schema.pattern ? schema.type.filter((t) => t !== 'string') : schema.type;
    return [...new Set(types.map((t) => primitive(t, schema, indent)))].join(' | ');
  }
  if (schema.type) {
    return primitive(schema.type, schema, indent);
  }
  return schema.properties ? objectOf(schema, indent) : 'unknown';
}

const out = ['// Generated by scripts/gen-api.mjs from openapi.json. Not tracked, never edited.', ''];
for (const [name, schema] of Object.entries(schemas).sort(([a], [b]) => a.localeCompare(b))) {
  out.push(`export type ${ident(name)} = ${typeOf(schema)};`, '');
}

const json = (content) => content?.['application/json']?.schema;
const operations = [];
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  for (const [method, operation] of Object.entries(item)) {
    if (!operation?.operationId) {
      continue;
    }
    const ok = Object.entries(operation.responses ?? {}).find(([status]) => status.startsWith('2'));
    const body = json(operation.requestBody?.content);
    const result = ok ? json(ok[1].content) : undefined;
    const params = [...path.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((m) => m[1]);
    operations.push({ id: operation.operationId, method: method.toUpperCase(), path, body, result, params });
  }
}
operations.sort((a, b) => a.id.localeCompare(b.id));

out.push('export interface Operations {');
for (const op of operations) {
  out.push(`  ${ident(op.id)}: {`);
  out.push(`    params: ${op.params.length ? `{ ${op.params.map((p) => `${p}: number | string`).join('; ')} }` : 'undefined'};`);
  out.push(`    body: ${op.body ? typeOf(op.body, '    ') : 'undefined'};`);
  out.push(`    result: ${op.result ? typeOf(op.result, '    ') : 'undefined'};`);
  out.push('  };');
}
out.push('}', '', 'export const operations = {');
for (const op of operations) {
  out.push(`  ${ident(op.id)}: { method: ${JSON.stringify(op.method)}, path: ${JSON.stringify(op.path)} },`);
}
out.push('} as const satisfies Record<keyof Operations, { method: string; path: string }>;', '');

writeFileSync(fileURLToPath(new URL('src/api/schema.gen.ts', root)), out.join('\n'));
