using System.Text.RegularExpressions;
using Urlog.Core.Metadata;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;

namespace Urlog.Metadata.Tests;

/// <summary>
/// The same model builds against Npgsql and generates a script; the SQLite migration SQL carries no
/// SQLite-only construct; the snapshot carries no provider annotation; every identifier needs no quoting.
/// </summary>
public sealed partial class PortabilityTests(ITestOutputHelper output)
{
    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    private static readonly string[] Tables = ["users", "cases", "case_members", "hosts", "files", "jobs", "audit", "sessions"];

    [Fact]
    public void TheModelGeneratesAPostgresScript()
    {
        // A dummy connection string: GenerateCreateScript needs the provider's SQL generator, never a server.
        var options = new DbContextOptionsBuilder<MetadataDb>()
            .UseNpgsql("Host=localhost;Database=portability;Username=nobody;Password=nothing", o => o.MigrationsHistoryTable(MetadataDb.MigrationsHistoryTable))
            .Options;
        using var db = new MetadataDb(options);

        var script = db.Database.GenerateCreateScript();
        output.WriteLine(script);

        foreach (var table in Tables)
        {
            Assert.Matches(CreateTable(table), script);
        }

        Assert.Contains("bigint GENERATED BY DEFAULT AS IDENTITY", script, StringComparison.Ordinal);
        Assert.Contains("timestamp with time zone", script, StringComparison.Ordinal);
        Assert.Contains("CHECK (state IN ('active', 'closed', 'archived', 'soft_deleted', 'purging', 'purged'))", script, StringComparison.Ordinal);
        Assert.DoesNotContain("AUTOINCREMENT", script, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public async Task TheSqliteMigrationSqlHasNoSqliteOnlyConstruct()
    {
        await using var temp = TempDb.CreateUnmigrated();
        await using var db = temp.Open();
        var sql = db.GetService<IMigrator>().GenerateScript();
        output.WriteLine(sql);

        Assert.DoesNotContain("AUTOINCREMENT", sql, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("WITHOUT ROWID", sql, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("sqlite_", sql, StringComparison.OrdinalIgnoreCase);
        foreach (var table in Tables)
        {
            Assert.Matches(CreateTable(table), sql);
        }
    }

    [Fact]
    public async Task TheSnapshotCarriesNoProviderAnnotation()
    {
        await using var temp = TempDb.CreateUnmigrated();
        await using var db = temp.Open();
        var snapshot = db.GetService<IMigrationsAssembly>().ModelSnapshot;
        Assert.NotNull(snapshot);
        var model = snapshot.Model;

        var annotations = new List<string>(model.GetAnnotations().Select(a => a.Name));
        foreach (var entity in model.GetEntityTypes())
        {
            annotations.AddRange(entity.GetAnnotations().Select(a => a.Name));
            annotations.AddRange(entity.GetProperties().SelectMany(p => p.GetAnnotations()).Select(a => a.Name));
            annotations.AddRange(entity.GetKeys().SelectMany(k => k.GetAnnotations()).Select(a => a.Name));
            annotations.AddRange(entity.GetIndexes().SelectMany(i => i.GetAnnotations()).Select(a => a.Name));
            annotations.AddRange(entity.GetForeignKeys().SelectMany(f => f.GetAnnotations()).Select(a => a.Name));
        }

        Assert.DoesNotContain(annotations, a => a.StartsWith("Sqlite:", StringComparison.Ordinal) || a.StartsWith("Npgsql:", StringComparison.Ordinal));
        Assert.Equal(Tables.Length, model.GetEntityTypes().Count());
    }

    [Fact]
    public async Task EveryIdentifierIsLowercaseSnakeCase()
    {
        await using var temp = TempDb.CreateUnmigrated();
        await using var db = temp.Open();
        // Check constraints live on the design-time model only.
        var relational = db.GetService<IDesignTimeModel>().Model.GetRelationalModel();
        var names = new List<string>();
        foreach (var table in relational.Tables)
        {
            names.Add(table.Name);
            names.AddRange(table.Columns.Select(c => c.Name));
            names.AddRange(table.Indexes.Select(i => i.Name));
            names.AddRange(table.UniqueConstraints.Select(u => u.Name));
            names.AddRange(table.ForeignKeyConstraints.Select(f => f.Name));
            names.AddRange(table.CheckConstraints.Select(c => c.Name!));
        }

        names.Add(MetadataDb.MigrationsHistoryTable);
        Assert.NotEmpty(names);
        Assert.All(names, n => Assert.Matches(SnakeCase(), n));
        Assert.Equal(Tables.Order(), relational.Tables.Select(t => t.Name).Order());
    }

    private static Regex CreateTable(string table) => new($@"CREATE TABLE ""?{Regex.Escape(table)}""? \(", RegexOptions.None, TimeSpan.FromSeconds(1));

    [GeneratedRegex("^[a-z][a-z0-9_]*$")]
    private static partial Regex SnakeCase();
}
